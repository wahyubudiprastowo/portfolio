const { chromium } = require("playwright");
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.goto("http://localhost:3000/", { waitUntil: "networkidle" });
  await page.waitForTimeout(2600);
  await page.screenshot({ path: "/tmp/render/d1-hero.png" });
  await page.evaluate(() => window.scrollTo(0, document.getElementById("work").offsetTop - 40));
  await page.waitForTimeout(1200);
  await page.screenshot({ path: "/tmp/render/d2-work.png" });
  await page.evaluate(() => window.scrollTo(0, document.getElementById("numbers").offsetTop - 40));
  await page.waitForTimeout(1200);
  await page.screenshot({ path: "/tmp/render/d3-numbers.png" });
  await page.evaluate(() => window.scrollTo(0, document.getElementById("craft").offsetTop - 40));
  await page.waitForTimeout(1200);
  await page.screenshot({ path: "/tmp/render/d4-craft.png" });
  await page.evaluate(() => window.scrollTo(0, document.getElementById("journey").offsetTop - 40));
  await page.waitForTimeout(1200);
  await page.screenshot({ path: "/tmp/render/d5-journey.png" });
  await page.evaluate(() => window.scrollTo(0, document.getElementById("contact").offsetTop - 40));
  await page.waitForTimeout(1200);
  await page.screenshot({ path: "/tmp/render/d6-contact.png" });
  const errors = [];
  page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
  await page.screenshot({ path: "/tmp/render/d7-footer.png", fullPage: false });
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  await page.waitForTimeout(1000);
  await page.screenshot({ path: "/tmp/render/d7-footer.png" });
  console.log("console errors:", errors.length ? errors : "none");
  // mobile
  const mp = await browser.newPage({ viewport: { width: 375, height: 812 } });
  await mp.goto("http://localhost:3000/", { waitUntil: "networkidle" });
  await mp.waitForTimeout(2200);
  await mp.screenshot({ path: "/tmp/render/m1-hero.png" });
  await mp.evaluate(() => window.scrollTo(0, document.getElementById("numbers").offsetTop - 30));
  await mp.waitForTimeout(1000);
  await mp.screenshot({ path: "/tmp/render/m2-numbers.png" });
  await mp.evaluate(() => window.scrollTo(0, document.getElementById("contact").offsetTop - 30));
  await mp.waitForTimeout(1000);
  await mp.screenshot({ path: "/tmp/render/m3-contact.png" });
  await browser.close();
})();
